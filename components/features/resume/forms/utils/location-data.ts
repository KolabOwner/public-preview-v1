// Helper functions
export function getStateOptions(country: string): SelectOption[] {
  const countryCode = COUNTRY_NAME_TO_CODE[country] || country;
  
  if (countryCode === 'US') return US_STATES;
  if (countryCode === 'CA') return CANADA_PROVINCES;
  return [];
}

export function getStateLabel(country: string): string {
  const countryCode = COUNTRY_NAME_TO_CODE[country] || country;
  
  if (countryCode === 'US') return 'State';
  if (countryCode === 'CA') return 'Province';
  return 'State/Province';
}

export function isStateSelectionEnabled(country: string): boolean {
  const countryCode = COUNTRY_NAME_TO_CODE[country] || country;
  return countryCode === 'US' || countryCode === 'CA';
}

export function detectStateFromCity(city: string): string | undefined {
  return CITY_TO_STATE[city];
}

export function detectCountryFromState(state: string): string | undefined {
  const isUSState = US_STATES.some(s => s.value === state);
  const isCanadaProvince = CANADA_PROVINCES.some(p => p.value === state);
  
  if (isUSState) return 'US';
  if (isCanadaProvince) return 'CA';
  return undefined;
}